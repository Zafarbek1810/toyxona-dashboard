export function placeValue(region?: string, district?: string) {
  if (region && district) return `${region}|${district}`;
  return region || "";
}

export function parsePlace(value: string) {
  if (!value) return { region: undefined, district: undefined };
  const [region, district] = value.split("|");
  return { region: region || undefined, district: district || undefined };
}

export function placeLabel(value: string) {
  const { region, district } = parsePlace(value);
  return district || region || "Hudud";
}
